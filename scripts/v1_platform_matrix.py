@dataclass
class Cell:
    """One matrix cell with its truthful state and evidence."""

    state: str
    command: str
    observation: str
    reason: str = ""

    def as_dict(self) -> dict[str, Any]:
        return {
            "state": self.state,
            "command": self.command,
            "observation": self.observation,
            "reason": self.reason,
        }


@dataclass
class Evidence:
    host: dict[str, Any] = field(default_factory=dict)
    toolchains: dict[str, str] = field(default_factory=dict)
    agents: dict[str, dict[str, Any]] = field(default_factory=dict)
    browsers: dict[str, dict[str, Any]] = field(default_factory=dict)
    probes: dict[str, Cell] = field(default_factory=dict)
    generated_at: str = ""


def run(command: list[str], cwd: Path | None = None, timeout: int = 900) -> tuple[int, str]:
    """Runs a command and returns its exit code and combined output."""
    try:
        completed = subprocess.run(
            command,
            cwd=str(cwd) if cwd else None,
            capture_output=True,
            text=True,
            timeout=timeout,
            check=False,
        )
    except FileNotFoundError:
        return 127, "command not found"
    except subprocess.TimeoutExpired:
        return 124, "command timed out"
    output = (completed.stdout or "") + (completed.stderr or "")
    return completed.returncode, output.strip()


def probe_host() -> dict[str, Any]:
    return {
        "system": platform.system(),
        "release": platform.release(),
        "machine": platform.machine(),
        "platform": platform.platform(),
        "python": platform.python_version(),
        "node": os.uname().nodename if hasattr(os, "uname") else "unknown",
    }


def probe_toolchains() -> dict[str, str]:
    toolchains: dict[str, str] = {}
    probes = {
        "rustc": ["rustc", "--version"],
        "cargo": ["cargo", "--version"],
        "node": ["node", "--version"],
        "pnpm": ["pnpm", "--version"],
        "python": ["python3", "--version"],
    }
    for name, command in probes.items():
        if shutil.which(command[0]) is None:
            toolchains[name] = "NOT INSTALLED"
            continue
        code, output = run(command, timeout=60)
        toolchains[name] = output if code == 0 else f"FAILED ({code})"
    return toolchains


def probe_agents() -> dict[str, dict[str, Any]]:
    agents: dict[str, dict[str, Any]] = {}
    for agent, executables in AGENT_EXECUTABLES.items():
        found: dict[str, Any] = {
            "executable": None,
            "version": None,
            "state": "NOT INSTALLED",
            "command": "",
            "observation": "",
        }
        for executable in executables:
            path = shutil.which(executable)
            if path is None:
                continue
            found["executable"] = executable
            command = [executable, "--version"]
            code, output = run(command, timeout=60)
            found["command"] = " ".join(command)
            if code == 0:
                found["version"] = output.splitlines()[0] if output else "unknown"
                found["state"] = "PRESENT"
                found["observation"] = output.splitlines()[0] if output else ""
            else:
                found["state"] = "PRESENT BUT UNREPORTED"
                found["observation"] = output[:200]
            break
        agents[agent] = found
    return agents


