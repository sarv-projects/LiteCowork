def tail(output: str, lines: int = 6) -> str:
    trimmed = output.strip().splitlines()
    return "\n".join(trimmed[-lines:]) if trimmed else ""


def build_evidence() -> Evidence:
    evidence = Evidence()
    evidence.generated_at = time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime())
    evidence.host = probe_host()
    evidence.toolchains = probe_toolchains()
    evidence.agents = probe_agents()
    evidence.browsers = probe_browsers()
    evidence.probes["os_credential_store"] = probe_secret_service()
    evidence.probes["backup_restore"] = probe_backup_restore()
    evidence.probes["packaging"] = probe_packaging()
    evidence.probes["secret_scan"] = probe_secret_scan()
    return evidence


def host_platform(evidence: Evidence) -> tuple[str, str]:
    """The (system, architecture) key of the probing host."""
    return evidence.host["system"].lower(), evidence.host["machine"]


def platform_cell(evidence: Evidence, capability: str) -> Cell:
    """Resolves one capability cell for the operating system of this host."""
    host = evidence.host
    if capability == "backup_restore":
        return evidence.probes["backup_restore"]
    if capability == "packaging":
        return evidence.probes["packaging"]
    if capability == "secret_scan":
        return evidence.probes["secret_scan"]
    credential = evidence.probes["os_credential_store"]
    if credential.state != "PASSED":
        return Cell(
            state="BLOCKED",
            command="see docs/ACCEPTANCE-AND-E2E-PLAN.md",
            observation=credential.observation,
            reason=(
                "the OS credential store is unavailable on this host, so the daemon cannot "
                "reach a state where this capability can be exercised"
            ),
        )
    return Cell(
        state="NOT RUN",
        command=f"see docs/ACCEPTANCE-AND-E2E-PLAN.md for the exact {capability} command",
        observation="not exercised by this generator",
        reason=(
            "this capability needs a qualified operator with the real provider and a real "
            f"{host['system']} desktop session"
        ),
    )


def render(evidence: Evidence) -> str:
    host = evidence.host
    lines: list[str] = []
    lines.append("# LiteCowork desktop/local V1 release qualification matrix")
    lines.append("")
    lines.append(
        "This file is generated. Do not edit it by hand: run the command below to regenerate it."
    )
    lines.append("")
    lines.append("```")
    lines.append(
        "python3 scripts/v1_platform_matrix.py "
        "--out docs/release/QUALIFICATION-MATRIX.md "
        "--evidence-out /tmp/litecowork-release-evidence"
    )
    lines.append("```")
    lines.append("")
    lines.append(f"- Generated at: `{evidence.generated_at}`")
    lines.append(
        f"- Probing host: `{host['system']} {host['release']} {host['machine']}` "
        f"(python {host['python']})"
    )
    lines.append(
        "- A cell is `PASSED` only when the probe actually ran on this host and observed "
        "success. Every other cell carries the reason it is not a pass."
    )
    lines.append("- `NOT RUN` means the probe exists but was not executed here.")
    lines.append("- `BLOCKED` means the environment cannot run the probe at all.")
    lines.append("")
    lines.append("## Toolchain observed on the probing host")
    lines.append("")
    lines.append("| Tool | Observed |")
    lines.append("|---|---|")
    for name, value in sorted(evidence.toolchains.items()):
        lines.append(f"| {name} | `{value}` |")
    lines.append("")

    lines.append("## Platform capability matrix")
    lines.append("")
    host_system, host_machine = host_platform(evidence)
    wsl = "wsl" in host["release"].lower() or "microsoft" in host["release"].lower()

    def column_label(system: str, arch: str) -> str:
        label = f"{system}/{arch}"
        if system == host_system and wsl:
            label += " (wsl2)"
        return label

    header = "| Capability | " + " | ".join(
        column_label(system, arch) for system, arch in SUPPORTED_PLATFORMS
    ) + " |"
    lines.append(header)
    lines.append("|---" * (len(SUPPORTED_PLATFORMS) + 1) + "|")
    for capability in CAPABILITIES:
        cells: list[str] = []
        for system, arch in SUPPORTED_PLATFORMS:
            if system == "macos":
                cells.append("UNSUPPORTED")
            elif system == host_system:
                cells.append(platform_cell(evidence, capability).state)
            else:
                cells.append("BLOCKED")
        lines.append(f"| {capability} | " + " | ".join(cells) + " |")
    lines.append("")
    if "wsl" in host["release"].lower() or "microsoft" in host["release"].lower():
        lines.append(
            "> **Host note:** this probing host is a WSL2 environment, not a native Linux "
            "desktop kernel. Process isolation, file identity, PTY and browser takeover "
            "behaviour on WSL2 is not the behaviour on a native Linux desktop, so a cell "
            "probed here is not a native Linux desktop qualification."
        )
        lines.append("")
    lines.append("### Per-cell evidence for the probed host")
    lines.append("")
    for capability in CAPABILITIES:
        cell = platform_cell(evidence, capability)
        lines.append(f"#### {capability}")
        lines.append("")
        lines.append(f"- State: **{cell.state}**")
        lines.append(f"- Command: `{cell.command}`")
        if cell.observation:
            lines.append("- Observation:")
            lines.append("")
            lines.append("```")
            lines.append(cell.observation)
            lines.append("```")
        if cell.reason:
            lines.append(f"- Reason: {cell.reason}")
        lines.append("")

    lines.append("## Agent and harness matrix")
    lines.append("")
    lines.append(
        "An agent is only supported when its exact version passes the native harness "
        "conformance on the exact operating system. A detected version is an "
        "observation, not a qualification."
    )
    lines.append("")
    lines.append("| Agent | Executable | Observed version | State |")
    lines.append("|---|---|---|---|")
    for agent, facts in sorted(evidence.agents.items()):
        lines.append(
            f"| {agent} | `{facts['executable'] or '-'}` | "
            f"`{facts['version'] or '-'}` | {facts['state']} |"
        )
    lines.append("")

    lines.append("## Hosted agent provider matrix")
    lines.append("")
    lines.append(
        "A hosted agent provider runs the agent in the provider's own environment. "
        "LiteCowork connects the owner account, leases the authority it needs, and "
        "receives only what the provider exposes. Support is claimed per exact provider, "
        "capability, and plan, never per brand."
    )
    lines.append("")
    lines.append("| Provider | State | Reason |")
    lines.append("|---|---|---|")
    for provider in HOSTED_AGENT_PROVIDERS:
        lines.append(
            f"| {provider} | NOT QUALIFIED | no provider conformance record |"
        )
    lines.append("")

    lines.append("## Browser matrix")
    lines.append("")
    lines.append("| Browser | Executable | Observed version | State |")
    lines.append("|---|---|---|---|")
    for browser, facts in sorted(evidence.browsers.items()):
        lines.append(
            f"| {browser} | `{facts['executable'] or '-'}` | "
            f"`{facts['version'] or '-'}` | {facts['state']} |"
        )
    lines.append("")

    lines.append("## Cells that are not a pass")
    lines.append("")
    lines.append("| Capability | State | Reason |")
    lines.append("|---|---|---|")
    for capability in CAPABILITIES:
        cell = platform_cell(evidence, capability)
        if cell.state == "PASSED":
            continue
        lines.append(f"| {capability} | {cell.state} | {cell.reason or '-'} |")
    lines.append("")
    return "\n".join(lines)


